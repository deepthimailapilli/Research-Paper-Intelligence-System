"""PDF / Word report export. One list of 'blocks' is built from an analysis, a comparison or a
literature review, then rendered to either format. reportlab and python-docx are imported lazily so
the rest of the app still starts if they are not installed yet."""
import re
from datetime import date
from io import BytesIO
from xml.sax.saxutils import escape

from . import compare

CTRL = re.compile(r"[\x00-\x08\x0b\x0c\x0e-\x1f]")
PUNCT = {"\u2018": "'", "\u2019": "'", "\u201c": '"', "\u201d": '"', "\u2013": "-", "\u2014": "-", "\u2026": "...",
         "\u2022": "-", "\u00d7": "x", "\u00a0": " ", "\u2212": "-"}


def _c(x):
    return CTRL.sub("", str(x if x is not None else ""))


def _l(x):
    return [_c(i) for i in (x or []) if str(i).strip()]


# ---------- blocks ----------
# ("title", text) ("meta", text) ("h1", text) ("h2", text) ("p", text) ("kv", label, text)
# ("ul", [items]) ("table", header[], rows[[cell]], note)   cell = {"chips": [...], "lists": [{"label", "items"}], "shared": set}
def _analysis_blocks(d, title):
    B, ki = [], d.get("key_info")
    if d.get("note"):
        B.append(("p", d["note"]))
    if d.get("summary"):
        B += [("h1", "Summary"), ("p", d["summary"])]
        if d.get("section_summaries"):
            B.append(("h1", "Section-wise summary"))
            for k, v in d["section_summaries"].items():
                B += [("h2", k), ("p", v)]
    if ki:
        b, m, n = ki.get("Basics", {}), ki.get("Models, data & metrics", {}), ki.get("Named entities", {})
        B += [("h1", "Key information"), ("kv", "Title", b.get("Title", "")),
              ("kv", "Authors", ", ".join(b.get("Authors", []))), ("kv", "Important dates", "; ".join(b.get("Important dates", []))),
              ("kv", "Keywords", ", ".join(b.get("Keywords", []))),
              ("kv", "Methods / models", ", ".join(m.get("Models / methods", []))),
              ("kv", "Datasets", "; ".join(m.get("Datasets", []))), ("kv", "Metrics", ", ".join(m.get("Metrics", []))),
              ("kv", "Databases", ", ".join(m.get("Databases", []))),
              ("kv", "Organizations", ", ".join(n.get("Organizations", []))), ("kv", "Locations", ", ".join(n.get("Locations", []))),
              ("kv", "Products", ", ".join(n.get("Products", [])))]
    if d.get("extraction"):
        B.append(("h1", "Extraction"))
        for k, v in d["extraction"].items():
            B += [("h2", k), ("ul", v)]
    if d.get("gap_analysis"):
        B.append(("h1", "Research gap"))
        for k, v in d["gap_analysis"].items():
            B += [("h2", k), ("ul", v)]
    return B


def _review_blocks(rv):
    B = [("h1", "Literature review (draft)")]
    B += [("p", t) for t in re.split(r"\n\n+", rv.get("text", "")) if t.strip()]
    B += [("h2", "References (APA)")] + [("p", r) for r in rv.get("references", [])]
    if rv.get("note"):
        B.append(("meta", rv["note"]))
    return B


def blocks(kind, data, title="", notes=""):
    data = data or {}
    if kind == "compare":
        papers = data.get("papers") or []
        if len(papers) < 2:
            raise ValueError("A comparison needs at least 2 papers")
        rows = compare.rows(papers)
        head = [f"{i}. {p.get('title') or p.get('name')}" + (f" ({p['year']})" if p.get("year") else "") for i, p in enumerate(papers, 1)]
        table = [(r["label"], [dict(c, shared={s for s in r.get("shared", [])}) for c in r["cells"]]) for r in rows]
        B = [("title", title or "Paper comparison"), ("meta", _stamp()), ("table", head, table,
             "* appears in more than one paper")]
        if data.get("review"):
            B += _review_blocks(data["review"])
    elif kind == "review":
        B = [("title", title or "Literature review draft"), ("meta", _stamp())] + _review_blocks(data)
    else:
        ki = (data.get("key_info") or {}).get("Basics", {})
        pages = data.get("pages")
        B = [("title", title or ki.get("Title") or "Paper analysis"),
             ("meta", _stamp() + (f" | {pages} pages analyzed" if pages else ""))] + _analysis_blocks(data, title)
    if notes and notes.strip():
        B += [("h1", "My notes"), ("p", notes)]
    return B


def _stamp():
    return f"Generated by Research Assistant on {date.today():%d %B %Y}"


# ---------- cell text ----------
def _cell_lines(cell):
    """-> list of (bold_label|None, text) lines"""
    lines = []
    shared = cell.get("shared") or set()
    if cell.get("chips"):
        lines.append((None, ", ".join(_c(x) + ("*" if x.lower() in shared else "") for x in cell["chips"])))
    for lst in cell.get("lists", []):
        items = _l(lst.get("items"))
        if not items:
            continue
        if lst.get("label"):
            lines.append((lst["label"], ""))
        lines += [(None, "- " + i) for i in items]
    return lines or [(None, "Not found in the text")]


# ---------- Word ----------
def to_docx(B):
    from docx import Document
    from docx.enum.section import WD_ORIENT
    from docx.shared import Pt, Inches, RGBColor

    doc = Document()
    doc.styles["Normal"].font.name = "Calibri"
    doc.styles["Normal"].font.size = Pt(11)
    if any(b[0] == "table" for b in B):
        s = doc.sections[0]
        s.orientation = WD_ORIENT.LANDSCAPE
        s.page_width, s.page_height = s.page_height, s.page_width
        for side in ("left_margin", "right_margin", "top_margin", "bottom_margin"):
            setattr(s, side, Inches(0.7))
    for b in B:
        t = b[0]
        if t == "title":
            doc.add_heading(_c(b[1]), 0)
        elif t == "meta":
            r = doc.add_paragraph().add_run(_c(b[1]))
            r.italic, r.font.size, r.font.color.rgb = True, Pt(9), RGBColor(0x66, 0x6D, 0x8A)
        elif t in ("h1", "h2"):
            doc.add_heading(_c(b[1]), 1 if t == "h1" else 2)
        elif t == "p":
            doc.add_paragraph(_c(b[1]))
        elif t == "kv":
            if str(b[2]).strip():
                p = doc.add_paragraph()
                p.add_run(_c(b[1]) + ": ").bold = True
                p.add_run(_c(b[2]))
        elif t == "ul":
            items = _l(b[1]) or ["Not found in the text"]
            for i in items:
                doc.add_paragraph(i, style="List Bullet")
        elif t == "table":
            head, rows, note = b[1], b[2], b[3]
            tb = doc.add_table(rows=1, cols=len(head) + 1)
            tb.style = "Table Grid"
            for cell, txt in zip(tb.rows[0].cells, [""] + head):
                cell.text = ""
                cell.paragraphs[0].add_run(_c(txt)).bold = True
            for label, cells in rows:
                rc = tb.add_row().cells
                rc[0].text = ""
                rc[0].paragraphs[0].add_run(label).bold = True
                for cell, data in zip(rc[1:], cells):
                    cell.text = ""
                    first = True
                    for lab, txt in _cell_lines(data):
                        p = cell.paragraphs[0] if first else cell.add_paragraph()
                        first = False
                        if lab:
                            p.add_run(_c(lab)).bold = True
                        if txt:
                            p.add_run(_c(txt))
            if note:
                doc.add_paragraph().add_run(note).italic = True
    out = BytesIO()
    doc.save(out)
    return out.getvalue()


# ---------- PDF ----------
def _p(x):
    x = _c(x)
    for k, v in PUNCT.items():
        x = x.replace(k, v)
    return escape(x.encode("latin-1", "replace").decode("latin-1"))


def to_pdf(B):
    from reportlab.lib import colors
    from reportlab.lib.pagesizes import A4, landscape
    from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
    from reportlab.lib.units import mm
    from reportlab.platypus import Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle, KeepTogether

    ss = getSampleStyleSheet()
    ink, acc = colors.HexColor("#1f2340"), colors.HexColor("#4f46e5")
    st = {"title": ParagraphStyle("t", parent=ss["Title"], fontSize=20, leading=24, textColor=colors.HexColor("#1b1747"), alignment=0, spaceAfter=4),
          "meta": ParagraphStyle("m", parent=ss["Normal"], fontSize=8.5, textColor=colors.HexColor("#666d8a"), spaceAfter=10),
          "h1": ParagraphStyle("h1", parent=ss["Heading1"], fontSize=15, leading=19, textColor=acc, spaceBefore=14, spaceAfter=6),
          "h2": ParagraphStyle("h2", parent=ss["Heading2"], fontSize=11.5, leading=15, textColor=ink, spaceBefore=8, spaceAfter=3),
          "p": ParagraphStyle("p", parent=ss["Normal"], fontSize=10, leading=14.5, spaceAfter=6),
          "li": ParagraphStyle("li", parent=ss["Normal"], fontSize=10, leading=14, leftIndent=14, bulletIndent=3, spaceAfter=3),
          "cell": ParagraphStyle("c", parent=ss["Normal"], fontSize=8, leading=10.5, spaceAfter=1.5),
          "hd": ParagraphStyle("hd", parent=ss["Normal"], fontSize=8.5, leading=11, textColor=colors.white, fontName="Helvetica-Bold")}
    wide = any(b[0] == "table" for b in B)
    page = landscape(A4) if wide else A4
    buf = BytesIO()
    doc = SimpleDocTemplate(buf, pagesize=page, leftMargin=16 * mm, rightMargin=16 * mm, topMargin=16 * mm, bottomMargin=16 * mm,
                            title="Research Assistant report")
    story = []
    for b in B:
        t = b[0]
        if t in ("title", "meta", "h1", "h2", "p"):
            story.append(Paragraph(_p(b[1]).replace("\n", "<br/>"), st[t]))
        elif t == "kv":
            if str(b[2]).strip():
                story.append(Paragraph(f"<b>{_p(b[1])}:</b> {_p(b[2])}", st["p"]))
        elif t == "ul":
            for i in _l(b[1]) or ["Not found in the text"]:
                story.append(Paragraph(_p(i), st["li"], bulletText="\u2022"))
        elif t == "table":
            head, rows, note = b[1], b[2], b[3]
            data = [[Paragraph("", st["hd"])] + [Paragraph(_p(h), st["hd"]) for h in head]]
            for label, cells in rows:
                row = [Paragraph(f"<b>{_p(label)}</b>", st["cell"])]
                for c in cells:
                    html = "<br/>".join((f"<b>{_p(lab)}</b> " if lab else "") + _p(txt) for lab, txt in _cell_lines(c))
                    row.append(Paragraph(html, st["cell"]))
                data.append(row)
            avail = page[0] - 32 * mm
            first = 24 * mm
            tb = Table(data, colWidths=[first] + [(avail - first) / len(head)] * len(head), repeatRows=1, splitByRow=1)
            tb.setStyle(TableStyle([("BACKGROUND", (0, 0), (-1, 0), acc), ("BACKGROUND", (0, 1), (0, -1), colors.HexColor("#f1efff")),
                                    ("GRID", (0, 0), (-1, -1), 0.4, colors.HexColor("#cfcbe8")), ("VALIGN", (0, 0), (-1, -1), "TOP"),
                                    ("LEFTPADDING", (0, 0), (-1, -1), 5), ("RIGHTPADDING", (0, 0), (-1, -1), 5),
                                    ("TOPPADDING", (0, 0), (-1, -1), 4), ("BOTTOMPADDING", (0, 0), (-1, -1), 4)]))
            story += [tb, Spacer(1, 4)]
            if note:
                story.append(Paragraph(_p(note), st["meta"]))

    def footer(canvas, d):
        canvas.saveState()
        canvas.setFont("Helvetica", 8)
        canvas.setFillColor(colors.HexColor("#666d8a"))
        canvas.drawRightString(page[0] - 16 * mm, 9 * mm, f"Page {d.page}")
        canvas.restoreState()

    doc.build(story, onFirstPage=footer, onLaterPages=footer)
    return buf.getvalue()
